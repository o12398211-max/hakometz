function rnd(arr, r = Math.random) { return arr[Math.floor(r() * arr.length)]; }

function makeNpc(i) {
  const name = NAMES[i % NAMES.length];
  return {
    id: 'npc' + i,
    name,
    avatar: { color: rnd(COLORS), emoji: '' },
    profile: { age: 19 + Math.floor(Math.random() * 50), job: rnd(JOBS), city: rnd(CITIES) },
    npc: true,
  };
}

// הסתברות לענות נכון לפי אחוז השאלה. מעט "חותך" יותר בשאלות הקשות
function npcCorrectProb(level) {
  const p = level / 100;
  return Math.max(0.005, Math.min(0.985, p * 1.02));
}

